/**
 * Scores the setup screen's judge tier (setup-command-specs.ts) against a
 * labelled corpus, through the exact production request (server askNouls +
 * core specs + resolveSetupAnswers). Rerun after touching an ask, an example,
 * the situation or a threshold: the asks share one request, so an edit to one
 * can move the others.
 *
 *   npm run jev:setup -- [--cache <dir>] [--budget 0.40] [--dry] [--misheard-limit 150] [--out <file.json>]
 *
 * Needs TYPESAFE_API_KEY, from ts/server/.env or the environment. Answers are
 * cached on disk per (spec version, text), so an unchanged line is never asked
 * twice, and the cache dir keeps a running total of what has been spent
 * (spent.json); asking stops once that total reaches --budget.
 *
 * Only lines the on-device parser misses are scored: the setup view asks the
 * judge only after parseSetupCommand returns null. Sections:
 * - CLEAN: natural phrasings outside the parser's grammar.
 * - MISHEARD: what local Whisper wrote for setup requests the parser then
 *   missed (setup-voice/misheard.ts, generated by setup-voice/run.ts, when it
 *   exists), plus mishearings invented here, marked as such.
 * - NEGATIVES: room and television talk, meditation-adjacent talk, near
 *   misses (setup-voice/phrases.ts NEGATIVES and PROSE, plus more here).
 * - BEGIN-LIKE: every one must come to nothing. Begin is never this tier's.
 *
 * Prints misses, false positives (the number that matters: asks loose enough
 * for sound-alikes are loose enough for a television), the thinnest margin on
 * each side of each bar, tokens and cost per call, and what this run spent.
 */

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { judgeQuestions, judgeState, type JudgeAnswers } from '../src/facilitation/utterance-judge.js';
import {
    mightBeSetupRequest,
    resolveSetupAnswers,
    SETUP_GATE_ASK,
    SETUP_GATE_BAR,
    SETUP_SPECS,
    type SetupJudgeId,
} from '../src/facilitation/setup-command-specs.js';
import type { SetupAction, SetupFocus } from '../src/facilitation/setup-command.js';
import { askNouls, JEV_USD_PER_INPUT_TOKEN } from '../server/src/providers/typesafe.js';
import { loadServerEnv } from '../soak/env.js';
import { corpus, misheard, normalize, skipped, type Case } from './setup-judge-corpus.js';

// ---- options ----------------------------------------------------------------

const argv = process.argv.slice(2);
const flag = (name: string): string | undefined => {
    const at = argv.indexOf(name);
    return at >= 0 ? argv[at + 1] : undefined;
};
const CACHE_DIR = flag('--cache') ?? process.env['JEV_SETUP_CACHE'] ?? join(tmpdir(), 'aloud-jev-setup-cache');
const BUDGET_USD = Number(flag('--budget') ?? '0.40');
const DRY = argv.includes('--dry');
/** Every scored line as JSON, for looking at thresholds without asking again. */
const OUT = flag('--out');
/** Negatives the gate scores under this skip the full set: the gate already
 *  stops them, and the full set's margins matter where the gate lets through. */
const MEASURE_FLOOR = Math.min(SETUP_GATE_BAR, 0.1);

// ---- cache + spending -------------------------------------------------------

mkdirSync(CACHE_DIR, { recursive: true });
interface Cached {
    answers: JudgeAnswers;
    tokens: number;
}
function specVersion(id: SetupJudgeId): string {
    return createHash('sha256')
        .update(JSON.stringify({ situation: SETUP_SPECS[id].situation, questions: judgeQuestions(id) }))
        .digest('hex')
        .slice(0, 12);
}
const caches = new Map<SetupJudgeId, { file: string; data: Record<string, Cached> }>();
for (const id of ['setup-gate', 'setup-command'] as const) {
    const file = join(CACHE_DIR, `${id}-${specVersion(id)}.json`);
    caches.set(id, { file, data: existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as Record<string, Cached>) : {} });
}
const SPENT_FILE = join(CACHE_DIR, 'spent.json');
interface Spent {
    usd: number;
    calls: number;
    tokens: number;
}
const spent: Spent = existsSync(SPENT_FILE) ? (JSON.parse(readFileSync(SPENT_FILE, 'utf8')) as Spent) : { usd: 0, calls: 0, tokens: 0 };
const run: Spent = { usd: 0, calls: 0, tokens: 0 };
const tokensPerCall: Partial<Record<SetupJudgeId, number>> = {};
let overBudget = false;

function save(): void {
    for (const { file, data } of caches.values()) writeFileSync(file, JSON.stringify(data));
    writeFileSync(SPENT_FILE, JSON.stringify(spent, null, 1));
}

loadServerEnv();
const key = process.env['TYPESAFE_API_KEY'];
if (!key && !DRY) throw new Error('TYPESAFE_API_KEY not set');

async function ask(id: SetupJudgeId, text: string): Promise<JudgeAnswers | null> {
    const cache = caches.get(id)!;
    const hit = cache.data[text];
    if (hit) {
        tokensPerCall[id] = hit.tokens;
        return hit.answers;
    }
    if (DRY) return null;
    if (spent.usd >= BUDGET_USD) {
        overBudget = true;
        return null;
    }
    for (let attempt = 0; attempt < 3; attempt++) {
        try {
            const r = await askNouls(key!, judgeState(id, text), judgeQuestions(id));
            const usd = r.inputTokens * JEV_USD_PER_INPUT_TOKEN;
            for (const s of [spent, run]) {
                s.usd += usd;
                s.calls += 1;
                s.tokens += r.inputTokens;
            }
            tokensPerCall[id] = r.inputTokens;
            cache.data[text] = { answers: r.answers, tokens: r.inputTokens };
            return r.answers;
        } catch {
            // Retry: a timeout says nothing about the ask. Failed attempts are
            // unbilled upstream only if they never got there; count nothing.
        }
    }
    return null;
}

// ---- the estimate -----------------------------------------------------------

const judged = corpus.filter((c) => mightBeSetupRequest(c.text));
const uncachedGate = judged.filter((c) => !caches.get('setup-gate')!.data[c.text]).length;
const uncachedFull = judged.filter((c) => !caches.get('setup-command')!.data[c.text]).length;
const estGate = 650 * JEV_USD_PER_INPUT_TOKEN;
const estFull = 4300 * JEV_USD_PER_INPUT_TOKEN;
console.log(
    `corpus: ${corpus.length} lines (${judged.length} reach the judge); parser took ${skipped.parserTook}, ` +
        `${skipped.duplicate} duplicates, ${skipped.unreachable} misheard lines not reachable by asks (intention, a guidance stop, a bare clear), ` +
        `${skipped.limit} past --misheard-limit; misheard.ts ${misheard ? `present (${misheard.length} tuples)` : 'absent'}`
);
console.log(
    `to ask: ${uncachedGate} gate + at most ${uncachedFull} full, at most $${(uncachedGate * estGate + uncachedFull * estFull).toFixed(4)}; ` +
        `spent so far $${spent.usd.toFixed(4)} of $${BUDGET_USD.toFixed(2)}`
);
if (DRY) process.exit(0);

// ---- run --------------------------------------------------------------------

interface Result {
    c: Case;
    pGate: number | null;
    full: JudgeAnswers | null;
    got: SetupAction[] | null;
    prefiltered: boolean;
}

async function score(c: Case): Promise<Result> {
    if (!mightBeSetupRequest(c.text)) return { c, pGate: null, full: null, got: null, prefiltered: true };
    const gate = await ask('setup-gate', c.text);
    const pGate = gate?.[SETUP_GATE_ASK] ?? null;
    const wantsFull = c.expect !== null || (pGate !== null && pGate >= MEASURE_FLOOR);
    const full = wantsFull ? await ask('setup-command', c.text) : null;
    const got = pGate !== null && pGate >= SETUP_GATE_BAR && full ? resolveSetupAnswers(full, c.text) : null;
    return { c, pGate, full, got, prefiltered: false };
}

const results: Result[] = [];
const POOL = 4;
for (let i = 0; i < corpus.length; i += POOL) {
    results.push(...(await Promise.all(corpus.slice(i, i + POOL).map(score))));
    if (i % 40 === 0) save();
}
save();
if (OUT) {
    writeFileSync(
        OUT,
        JSON.stringify(
            results.map((r) => ({ ...r.c, pGate: r.pGate, full: r.full, got: r.got, prefiltered: r.prefiltered })),
            null,
            1
        )
    );
}

// ---- report -----------------------------------------------------------------

const fmt = (a: SetupAction[] | null): string => (a ? a.map(normalize).join(' ') : 'null');
const same = (a: SetupAction[] | null, b: SetupAction[] | null): boolean => {
    if (!a || !b) return a === b;
    const x = new Set(a.map(normalize));
    const y = new Set(b.map(normalize));
    return x.size === y.size && [...x].every((k) => y.has(k));
};
const topAsks = (full: JudgeAnswers | null): string =>
    full
        ? Object.entries(full)
              .sort((a, b) => b[1] - a[1])
              .slice(0, 4)
              .map(([k, v]) => `${k}=${v.toFixed(2)}`)
              .join(' ')
        : '';

type Outcome = 'exact' | 'partial' | 'wrong' | 'miss' | 'gated' | 'error';
function outcome(r: Result): Outcome {
    if (r.c.expect === null) return r.got ? 'wrong' : 'exact';
    if (!r.prefiltered && (r.pGate === null || !r.full)) return 'error';
    if (same(r.got, r.c.expect)) return 'exact';
    if (!r.got) return r.pGate !== null && r.pGate < SETUP_GATE_BAR ? 'gated' : 'miss';
    const want = new Set(r.c.expect.map(normalize));
    return r.got.every((a) => want.has(normalize(a))) ? 'partial' : 'wrong';
}

for (const section of ['clean', 'clean-heldout', 'misheard', 'misheard-observed', 'misheard-invented', 'misheard-heldout'] as const) {
    const rs = results.filter((r) => r.c.section === section);
    if (rs.length === 0) continue;
    const counts: Record<Outcome, number> = { exact: 0, partial: 0, wrong: 0, miss: 0, gated: 0, error: 0 };
    console.log(`\n== ${section.toUpperCase()} (${rs.length})`);
    for (const r of rs) {
        const o = outcome(r);
        counts[o]++;
        if (o === 'exact') continue;
        console.log(
            `  ${o.toUpperCase().padEnd(7)} "${r.c.text}"${r.c.said ? ` (said "${r.c.said}")` : ''}\n` +
                `          want ${fmt(r.c.expect)}  got ${fmt(r.got)}  gate=${r.pGate?.toFixed(2) ?? '-'}  ${topAsks(r.full)}`
        );
    }
    console.log(
        `  ${counts.exact}/${rs.length} exact, ${counts.partial} partial, ${counts.wrong} WRONG, ` +
            `${counts.miss} missed by the set, ${counts.gated} stopped at the gate, ${counts.error} errors`
    );
}

/**
 * Misfires accepted on purpose, reported but not counted: stop-listening sits
 * under the other bars (setup-command-specs.ts THRESHOLDS), since all a false
 * one does is close the mic.
 */
const KNOWN_FP = new Set(['Stop, listen.', 'Put it on mute.']);

for (const section of ['negative', 'negative-heldout', 'begin-like'] as const) {
    const rs = results.filter((r) => r.c.section === section);
    for (const r of rs.filter((x) => x.got && KNOWN_FP.has(x.c.text))) {
        console.log(`  KNOWN "${r.c.text}"  got ${fmt(r.got)}`);
    }
    const fps = rs.filter((r) => r.got && !KNOWN_FP.has(r.c.text));
    const prefiltered = rs.filter((r) => r.prefiltered).length;
    const passedGate = rs.filter((r) => r.pGate !== null && r.pGate >= SETUP_GATE_BAR).length;
    console.log(
        `\n== ${section.toUpperCase()} (${rs.length}; ${prefiltered} never sent, ${passedGate} passed the gate): ` +
            `${fps.length} FALSE POSITIVES`
    );
    for (const r of fps) console.log(`  FP  "${r.c.text}"  got ${fmt(r.got)}  gate=${r.pGate?.toFixed(2)}  ${topAsks(r.full)}`);
    const errors = rs.filter((r) => !r.prefiltered && r.pGate === null).length;
    if (errors) console.log(`  (${errors} gate errors)`);
}

// Thinnest margins. A positive's asks are the ones its expected actions need.
function expectedAsks(expect: SetupAction[]): Set<string> {
    const asks = new Set<string>();
    const focusKey: Record<SetupFocus, string> = { body_sensations: 'focus_body', emotions: 'focus_emotions', inner_parts: 'focus_parts' };
    for (const a of expect) {
        if (a.kind === 'mode') asks.add(`mode_${a.mode}`);
        else if (a.kind === 'quality') asks.add(`vibe_${a.quality}`);
        else if (a.kind === 'focus') asks.add(focusKey[a.focus]);
        else if (a.kind === 'clear') asks.add('replace');
        else if (a.kind === 'guidance') asks.add(a.to === 'up' ? 'guide_more' : 'guide_less');
        else if (a.kind === 'verbosity') asks.add(a.to === 'up' || a.to === 'high' ? 'longer' : 'shorter');
        else if (a.kind === 'length') asks.add('length');
        else if (a.kind === 'no-timer') asks.add('no_timer');
        else if (a.kind === 'checkins') asks.add('checkins');
        else if (a.kind === 'stop-listening') asks.add('stop_listening');
        else if (a.kind === 'help') asks.add('help');
        if ((a.kind === 'quality' || a.kind === 'focus' || a.kind === 'checkins') && !a.on) asks.add('remove');
    }
    return asks;
}

const thresholds = SETUP_SPECS['setup-command'].asks;
interface Edge {
    p: number;
    text: string;
}
const weakestYes = new Map<string, Edge>();
const strongestNo = new Map<string, Edge>();
for (const r of results) {
    if (!r.full) continue;
    // Where the gate already stops a line, its bar is not what keeps it out.
    if (!r.c.expect && (r.pGate === null || r.pGate < SETUP_GATE_BAR)) continue;
    const want = r.c.expect ? expectedAsks(r.c.expect) : new Set<string>();
    for (const [k, p] of Object.entries(r.full)) {
        if (want.has(k)) {
            if (!weakestYes.has(k) || p < weakestYes.get(k)!.p) weakestYes.set(k, { p, text: r.c.text });
        } else if (!strongestNo.has(k) || p > strongestNo.get(k)!.p) {
            strongestNo.set(k, { p, text: r.c.text });
        }
    }
}
console.log('\nper ask: bar | weakest yes (score, line) | strongest no (score, line)   [no: lines past the gate]');
for (const [k, a] of Object.entries(thresholds)) {
    const y = weakestYes.get(k);
    const n = strongestNo.get(k);
    console.log(
        `  ${k.padEnd(19)} ${a.threshold.toFixed(2)} | ${y ? `${y.p.toFixed(2)} "${y.text}"` : '-'}\n` +
            `  ${''.padEnd(19)}      | no: ${n ? `${n.p.toFixed(2)} "${n.text}"` : '-'}`
    );
}

const gatePos = results.filter((r) => r.c.expect && r.pGate !== null).sort((a, b) => a.pGate! - b.pGate!);
const gateNeg = results.filter((r) => !r.c.expect && r.pGate !== null).sort((a, b) => b.pGate! - a.pGate!);
console.log(`\ngate (bar ${SETUP_GATE_BAR}): weakest requests`);
for (const r of gatePos.slice(0, 6)) console.log(`  ${r.pGate!.toFixed(2)}  "${r.c.text}"`);
console.log('gate: strongest non-requests');
for (const r of gateNeg.slice(0, 8)) console.log(`  ${r.pGate!.toFixed(2)}  "${r.c.text}"`);

const usd = (t: number | undefined): string => (t ? `$${(t * JEV_USD_PER_INPUT_TOKEN).toFixed(6)}` : '-');
console.log(
    `\nper call: gate ${tokensPerCall['setup-gate'] ?? '-'} tokens (${usd(tokensPerCall['setup-gate'])}), ` +
        `full set ${tokensPerCall['setup-command'] ?? '-'} tokens (${usd(tokensPerCall['setup-command'])}), ` +
        `${Object.keys(thresholds).length} asks`
);
console.log(
    `this run: ${run.calls} calls, ${run.tokens} tokens, $${run.usd.toFixed(4)}; ` +
        `all runs in ${CACHE_DIR}: $${spent.usd.toFixed(4)} of $${BUDGET_USD.toFixed(2)}${overBudget ? '  BUDGET REACHED, some lines unasked' : ''}`
);
const fpTotal = results.filter((r) => r.c.expect === null && r.got && !KNOWN_FP.has(r.c.text)).length;
process.exitCode = fpTotal > 0 ? 1 : 0;
