async function ask(id: SetupJudgeId, text: string): Promise<JudgeAnswers | null> {
    const cache = caches.get(id)!;
    const hit = cache.data[text];
    if (hit) {
        tokensPerCall[id] = hit.tokens;
        return hit.answers;
    }
    if (DRY) return null;
    if (spent.usd >= BUDGET_USD) {
        overBudget = true;
        return null;
    }
    for (let attempt = 0; attempt < 3; attempt++) {
        try {
            const r = await askNouls(key!, judgeState(id, text), judgeQuestions(id));
            const usd = r.inputTokens * JEV_USD_PER_INPUT_TOKEN;
            for (const s of [spent, run]) {
                s.usd += usd;
                s.calls += 1;
                s.tokens += r.inputTokens;
            }
            tokensPerCall[id] = r.inputTokens;
            cache.data[text] = { answers: r.answers, tokens: r.inputTokens };
            return r.answers;
        } catch {
            // Retry: a timeout says nothing about the ask. Failed attempts are
            // unbilled upstream only if they never got there; count nothing.
        }
    }
    return null;
}

