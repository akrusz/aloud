/** Prose cut into the short pieces a listener would hand over. */
function prosePieces(): string[] {
    const out: string[] = [];
    for (const { lang, text } of PROSE) {
        const sentences = lang === 'zh' ? text.split(/[，。？]/u) : text.split(/(?<=[.?!,])\s+/);
        let piece: string[] = [];
        for (const s of sentences.map((x) => x.trim()).filter(Boolean)) {
            piece.push(s);
            const n = lang === 'zh' ? piece.join('').length : piece.join(' ').split(/\s+/).length;
            if (n >= (lang === 'zh' ? 8 : 6)) {
                out.push(piece.join(lang === 'zh' ? '，' : ' '));
                piece = [];
            }
        }
        if (piece.length) out.push(piece.join(lang === 'zh' ? '，' : ' '));
    }
    return out;
}

/** What the judge can produce at all: no intention, no guidance stop by name,
 *  no bare clear. */
export function reachable(expect: SetupAction[]): boolean {
    return expect.every((a) => {
        if (a.kind === 'intention') return false;
        if (a.kind === 'guidance') return a.to === 'up' || a.to === 'down';
        if (a.kind === 'verbosity') return a.to !== 'medium';
        if (a.kind === 'clear') return expect.some((b) => b.kind === (a.group === 'focus' ? 'focus' : 'quality'));
        return true;
    });
}

/** "brief" and "long" read as one step either way here. */
export function normalize(a: SetupAction): string {
    if (a.kind === 'verbosity') return `verbosity:${a.to === 'low' || a.to === 'down' ? 'down' : 'up'}`;
    return JSON.stringify(a, Object.keys(a).sort());
}

async function loadMisheard(): Promise<Array<readonly [string, string, 'begin' | SetupAction[]]> | null> {
    // A computed specifier: the file is generated and may not exist yet.
    const specifier = './setup-voice/misheard.js';
    try {
        const mod = (await import(specifier)) as { MISHEARD?: Array<readonly [string, string, 'begin' | SetupAction[]]> };
        return mod.MISHEARD ?? null;
    } catch {
        return null;
    }
}

export const corpus: Case[] = [];
export const skipped = { parserTook: 0, unreachable: 0, duplicate: 0, limit: 0 };
const seen = new Set<string>();
function add(c: Case): void {
    const key = c.text.trim().toLowerCase();
    if (seen.has(key)) {
        skipped.duplicate++;
        return;
    }
    // The view asks the judge only after the parser misses.
    if (parseSetupCommand(c.text) !== null) {
        skipped.parserTook++;
        if (c.expect !== null) console.log(`(parser takes it) ${c.text}`);
        if (c.expect === null) console.log(`(parser takes a line labelled null) ${c.text} -> ${JSON.stringify(parseSetupCommand(c.text))}`);
        return;
    }
    seen.add(key);
    corpus.push(c);
}

for (const [text, expect] of CLEAN) add({ text, expect, section: 'clean' });
for (const [text, expect] of CLEAN_HELDOUT) add({ text, expect, section: 'clean-heldout' });
export const misheard = await loadMisheard();
let misheardTaken = 0;
for (const [heard, said, expect] of misheard ?? []) {
    if (expect === 'begin') {
        add({ text: heard, expect: null, section: 'begin-like', said });
        continue;
    }
    if (!reachable(expect)) {
        skipped.unreachable++;
        continue;
    }
    if (misheardTaken >= MISHEARD_LIMIT) {
        skipped.limit++;
        continue;
    }
    const before = corpus.length;
    add({ text: heard, expect, section: 'misheard', said });
    if (corpus.length > before) misheardTaken++;
}
