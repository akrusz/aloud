const fmt = (a: SetupAction[] | null): string => (a ? a.map(normalize).join(' ') : 'null');
const same = (a: SetupAction[] | null, b: SetupAction[] | null): boolean => {
    if (!a || !b) return a === b;
    const x = new Set(a.map(normalize));
    const y = new Set(b.map(normalize));
    return x.size === y.size && [...x].every((k) => y.has(k));
};
const topAsks = (full: JudgeAnswers | null): string =>
    full
        ? Object.entries(full)
              .sort((a, b) => b[1] - a[1])
              .slice(0, 4)
              .map(([k, v]) => `${k}=${v.toFixed(2)}`)
              .join(' ')
        : '';

type Outcome = 'exact' | 'partial' | 'wrong' | 'miss' | 'gated' | 'error';
function outcome(r: Result): Outcome {
    if (r.c.expect === null) return r.got ? 'wrong' : 'exact';
    if (!r.prefiltered && (r.pGate === null || !r.full)) return 'error';
    if (same(r.got, r.c.expect)) return 'exact';
    if (!r.got) return r.pGate !== null && r.pGate < SETUP_GATE_BAR ? 'gated' : 'miss';
    const want = new Set(r.c.expect.map(normalize));
    return r.got.every((a) => want.has(normalize(a))) ? 'partial' : 'wrong';
}

