/**
 * Scores the setup screen's judge tier (setup-command-specs.ts) against a
 * labelled corpus, through the exact production request (server askNouls +
 * core specs + resolveSetupAnswers). Rerun after touching an ask, an example,
 * the situation or a threshold: the asks share one request, so an edit to one
 * can move the others.
 *
 *   npm run jev:setup -- [--cache <dir>] [--budget 0.40] [--dry] [--misheard-limit 150] [--out <file.json>]
 *
 * Needs TYPESAFE_API_KEY, from ts/server/.env or the environment. Answers are
 * cached on disk per (spec version, text), so an unchanged line is never asked
 * twice, and the cache dir keeps a running total of what has been spent
 * (spent.json); asking stops once that total reaches --budget.
 *
 * Only lines the on-device parser misses are scored: the setup view asks the
 * judge only after parseSetupCommand returns null. Sections:
 * - CLEAN: natural phrasings outside the parser's grammar.
 * - MISHEARD: what local Whisper wrote for setup requests the parser then
 *   missed (setup-voice/misheard.ts, generated by setup-voice/run.ts, when it
 *   exists), plus mishearings invented here, marked as such.
 * - NEGATIVES: room and television talk, meditation-adjacent talk, near
 *   misses (setup-voice/phrases.ts NEGATIVES and PROSE, plus more here).
 * - BEGIN-LIKE: every one must come to nothing. Begin is never this tier's.
 *
 * Prints misses, false positives (the number that matters: asks loose enough
 * for sound-alikes are loose enough for a television), the thinnest margin on
 * each side of each bar, tokens and cost per call, and what this run spent.
 */

