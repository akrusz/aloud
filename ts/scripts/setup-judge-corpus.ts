/**
 * The labelled corpus for the setup screen's second tier: what the on-device
 * parser (setup-command.ts) misses, and what should become of it. Shared by
 * the two readers that stand behind the parser, so both are scored on the same
 * lines: jev-setup.ts (the judge) and setup-local.ts (a local model).
 *
 * Only lines the parser misses are here: the setup view asks a second tier
 * only after parseSetupCommand returns null. Sections:
 * - CLEAN: natural phrasings outside the parser's grammar.
 * - MISHEARD: what local Whisper wrote for setup requests the parser then
 *   missed (setup-voice/misheard.ts, generated by setup-voice/run.ts, when it
 *   exists), plus mishearings invented here, marked as such.
 * - NEGATIVES: room and television talk, meditation-adjacent talk, near
 *   misses (setup-voice/phrases.ts NEGATIVES and PROSE, plus more here).
 * - BEGIN-LIKE: every one must come to nothing. Begin is never this tier's.
 *
 * `--misheard-limit <n>` (default 150) caps the generated mishearings.
 */

